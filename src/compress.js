// /compress — content codings that misbehave on purpose.
// RFC 9110 §8.4 (Content-Encoding) and §12.5.3 (Accept-Encoding); RFC 1952 (gzip), RFC 1950 (zlib, which
// is what the "deflate" coding means), RFC 1951 (raw DEFLATE, which is what many servers send instead),
// RFC 7932 (br), RFC 8878 (zstd). The document is deterministic and self-describing (64-byte lines, each
// starting with its own offset, like /range), and every flavor response states the plaintext's length and
// SHA-256 in headers, so a client can prove what it decoded. Stateless; the only per-isolate state is a small
// memo of compressed bytes. Helpers (json, bad, intParam, bodyCodeParam, withBase, sleep) come in from index.js.
//
// "The edge" below is Cloudflare's CDN, which sits between the client and this Worker. It is part of the
// experiment, and the family is designed around what it was observed to do (probed live 2026-09-01:
// docs/probe-compress-2026-09-01.txt, docs/spec-compress.md):
//  - it rewrites Accept-Encoding to "gzip, br" before the Worker runs and keeps a NORMALIZED copy of the
//    client's value in request.cf.clientAcceptEncoding: a canonical set in a fixed order, q-values dropped
//    (q=0 included — a refusal never reaches this server), x-gzip and case folded to gzip, "*" and an empty
//    value reported as absent, a value with any non-ASCII byte reported as absent, and zstd dropped from the
//    set entirely (even though it delivers zstd to a client that lists it);
//  - it removes one coding layer it recognizes (gzip, br, zstd) unless that normalized set lists the coding,
//    transcoding the body to identity — cache-control: no-transform notwithstanding — and that transcoding is
//    lossy for broken streams; a second declared layer (double) is delivered regardless;
//  - it decoded zlib deflate for every client probed, including one that asked for it (the deflate flavor
//    exists so that observation stays reproducible);
//  - it passes codings it does not recognize (x-gzip, badhttp) through untouched.
// So: send Accept-Encoding: gzip to receive the gzip flavors as bytes, and read each flavor's edge column
// for what a client without gzip got. The raw Accept-Encoding header is never negotiated from: behind the
// edge it carries no client information, and local wrangler dev has no edge and no clientAcceptEncoding, so
// the negotiating flavors (ok, bomb) only behave as documented against the real host.

