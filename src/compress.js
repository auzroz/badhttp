// Line k reads "{offset:08d} {length:08d} badhttp compress body" padded with '.' to 63 chars, then "\n";
// the document is cut at length. All ASCII, so string length == byte length.
export function plainDoc(length) {
  let out = '';
  for (let off = 0; off < length; off += LINE) {
    out += `${String(off).padStart(8, '0')} ${String(length).padStart(8, '0')} badhttp compress body`.padEnd(LINE - 1, '.') + '\n';
  }
  return out.slice(0, length);
}

async function sha256hex(bytes) {
  const d = await crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(d)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

async function encode(bytes, format) { // 'gzip' | 'deflate' (zlib-wrapped) | 'deflate-raw'
  const stream = new Blob([bytes]).stream().pipeThrough(new CompressionStream(format));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

function concat(...parts) {
  const out = new Uint8Array(parts.reduce((n, p) => n + p.byteLength, 0));
  let off = 0;
  for (const p of parts) { out.set(p, off); off += p.byteLength; }
  return out;
}

// Single-flight memo of promises for the artifacts a flood would otherwise recompute (the gzip of the
// default and maximum documents, and each bomb size — at most 34 keys, ~3 MB). Other lengths are computed
// per request and not kept.
const MEMO = new Map();
function memo(key, fn) {
  if (!MEMO.has(key)) MEMO.set(key, fn().catch((e) => { MEMO.delete(key); throw e; }));
  return MEMO.get(key);
}

async function bombBytes(mib) {
  const chunk = new Uint8Array(65536); // 1,024 copies of the 64-byte line
  const line = enc.encode(BOMB_LINE);
  for (let i = 0; i < 1024; i++) chunk.set(line, i * LINE);
  const total = mib * 1048576;
  let sent = 0;
  const src = new ReadableStream({
    pull(c) {
      if (sent >= total) { c.close(); return; }
      c.enqueue(chunk.slice());
      sent += chunk.byteLength;
    },
  });
  return new Uint8Array(await new Response(src.pipeThrough(new CompressionStream('gzip'))).arrayBuffer());
}

// The client's Accept-Encoding as the edge reports it (request.cf.clientAcceptEncoding): already a
// normalized set — no q-values, no "*", aliases folded — so parsing is a split. The q handling exists only
// so the function is correct on a raw header (RFC 9110 §12.4.2 qvalue grammar); nothing in production
// ever hands it one. null = the client sent none, or only things the edge dropped.
export function parseAcceptEncoding(header) {
  if (header === null || header === undefined) return null;
  const m = new Map();
  for (const part of header.split(',')) {
    const [tok, ...params] = part.trim().split(';');
    const name = tok.trim().toLowerCase();
    if (!name) continue;
    let q = 1;
    for (const p of params) {
      const mm = /^\s*q\s*=\s*(0(?:\.\d{0,3})?|1(?:\.0{0,3})?)\s*$/i.exec(p);
      if (mm) q = Number(mm[1]);
    }
    m.set(name === 'x-gzip' ? 'gzip' : name, q);
  }
  return m;
}

// 'gzip' when the set names it with q > 0, else 'identity'. (An RFC-perfect server would 406 when identity
// is refused as well; a refusal cannot reach this server — the edge drops q=0 entries — so it never does.)
export function negotiate(map) {
  if (map === null) return 'identity';
  const g = map.has('gzip') ? map.get('gzip') : map.has('*') ? map.get('*') : 0;
  return g > 0 ? 'gzip' : 'identity';
}

