function paramsOf(f) {
  if (f.param === 'size') return ['size'];
  if (f.param === 'fixed') return ['code', `length (only ${f.empty ? 0 : FIXED_LENGTH})`];
  return f.minLength ? [`length (${f.minLength}–1048576)`, 'code'] : ['length', 'code'];
}

